import type {StudyActivity} from '../domain/study';

export type ReasonActivity = StudyActivity & {sourceKey: 'true' | 'false'};

export const REASON_INSTRUCTION = 'Реши, верно ли исходное объяснение. Выбери формулировку правила и пример, который его подтверждает.';

function exercise({
 source, sourceVersion, sourceKey, word, choices, examples, explanation, hint,
}: {
 source: string;
 sourceVersion: number;
 sourceKey: ReasonActivity['sourceKey'];
 word: string;
 choices: NonNullable<StudyActivity['choices']>;
 examples: NonNullable<StudyActivity['examples']>;
 explanation: string;
 hint: string;
}): ReasonActivity {
 return {
  id: `reason.${source}`,
  version: 1,
  mode: 'reason',
  kind: 'repair',
  title: `Проверь рассуждение: ${word}`,
  instruction: REASON_INSTRUCTION,
  prompt: '',
  choices,
  key: 'right',
  examples,
  exampleKey: 'proof',
  explanation,
  hint,
  sourceTaskId: `rustutors-2026-2027-oge6-${source}`,
  sourceTaskVersion: sourceVersion,
  sourceKey,
  independent: true,
 };
}

